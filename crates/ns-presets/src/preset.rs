//! 供应商预设表。
//!
//! 每个预设提供工具、分类、名称/别名/域名、图标与一个构建函数：
//! 用户输入（endpoint/key/model）→ `settings_config` 关键字段对象。
//! 预设即数据，逻辑不感知具体供应商。

use serde_json::{Value, json};

use crate::{ProviderCategory, Tool};

/// 供应商预设。
#[derive(Debug, Clone, Copy)]
pub struct Preset {
    /// 预设标识（生成供应商 id 时加时间戳/序号后缀）。
    pub id: &'static str,
    /// 显示名（可含中文名）。
    pub name: &'static str,
    pub tool: Tool,
    pub category: ProviderCategory,
    /// 搜索别名（中文名、域名等）。
    pub aliases: &'static [&'static str],
    /// 图标名称。
    pub icon: &'static str,
    /// 图标颜色（Hex）。
    pub icon_color: &'static str,
    /// 网站（可选）。
    pub website_url: Option<&'static str>,
    /// 供应商行 → 目标关键字段。

    pub build: fn(endpoint: &str, key: &str, model: &str) -> Value,
    /// API 格式:anthropic / openai_chat / openai_responses / gemini_native。
    pub api_format: &'static str,
    /// Claude Desktop 模型映射(sonnet, opus, haiku 上游模型)。
    pub desktop_routes: Option<(&'static str, &'static str, &'static str)>,
}

/// 生成 `settingsConfig`：`env` 对象（Claude Code 风格）。
fn claude_env(endpoint: &str, key: &str, model: &str) -> Value {
    json!({
        "env": {
            "ANTHROPIC_BASE_URL": endpoint,
            "ANTHROPIC_AUTH_TOKEN": key,
            "ANTHROPIC_MODEL": model,
            "ANTHROPIC_SMALL_FAST_MODEL": "claude-haiku-4-5",
        }
    })
}

/// 生成 `settingsConfig`：Codex 风格 `{ auth, config }`。
fn codex_auth(endpoint: &str, key: &str, model: &str) -> Value {
    json!({
        "auth": {
            "OPENAI_API_KEY": key,
        },
        "config": {
            "model_provider": "custom",
            "model": model,
            "model_providers": {
                "custom": {
                    "name": "自定义",
                    "base_url": endpoint,
                    "wire_api": "chat",
                }
            }
        }
    })
}

/// 生成 `settingsConfig`：Gemini 风格（`settings.json` + `.env`）。
fn gemini_config(endpoint: &str, key: &str, model: &str) -> Value {
    json!({
        "env": {
            "GEMINI_API_KEY": key,
            "GEMINI_BASE_URL": endpoint,
            "GEMINI_MODEL": model,
        }
    })
}

/// 生成 `settingsConfig`：通用 JSON 工具(OpenCode/OpenClaw/Hermes/Pi 等)风格。
fn json_tool(endpoint: &str, key: &str, model: &str) -> Value {
    json!({
        "baseUrl": endpoint,
        "apiKey": key,
        "model": model,
    })
}

const fn preset(
    id: &'static str,
    name: &'static str,
    tool: Tool,
    category: ProviderCategory,
    aliases: &'static [&'static str],
    icon: &'static str,
    icon_color: &'static str,
    website_url: Option<&'static str>,
    build: fn(&str, &str, &str) -> Value,
) -> Preset {
    preset_fmt(
        id,
        name,
        tool,
        category,
        aliases,
        icon,
        icon_color,
        website_url,
        "anthropic",
        build,
    )
}

/// 带 API 格式的预设构造。
const fn preset_fmt(
    id: &'static str,
    name: &'static str,
    tool: Tool,
    category: ProviderCategory,
    aliases: &'static [&'static str],
    icon: &'static str,
    icon_color: &'static str,
    website_url: Option<&'static str>,
    api_format: &'static str,
    build: fn(&str, &str, &str) -> Value,
) -> Preset {
    Preset {
        id,
        name,
        tool,
        category,
        aliases,
        icon,
        icon_color,
        website_url,
        build,
        api_format,
        desktop_routes: None,
    }
}

/// Claude Desktop 预设构造(含模型映射)。
const fn preset_desktop(
    id: &'static str,
    name: &'static str,
    category: ProviderCategory,
    aliases: &'static [&'static str],
    icon: &'static str,
    icon_color: &'static str,
    website_url: Option<&'static str>,
    api_format: &'static str,
    routes: (&'static str, &'static str, &'static str),
    build: fn(&str, &str, &str) -> Value,
) -> Preset {
    Preset {
        id,
        name,
        tool: Tool::ClaudeDesktop,
        category,
        aliases,
        icon,
        icon_color,
        website_url,
        build,
        api_format,
        desktop_routes: Some(routes),
    }
}

